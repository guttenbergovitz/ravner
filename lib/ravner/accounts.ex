  end

  ## One-Time Login Links

  @doc """
  Determines if an actor is authorized to generate a one-time login link for a target user.
  """
  @spec can_generate_one_time_login?(User.t() | Scope.t(), User.t()) :: boolean()
  def can_generate_one_time_login?(actor, %User{} = target_user) do
    ScopeResolver.can_generate_one_time_login?(actor, target_user)
  end

  @doc """
  Generates a 48-hour secure one-time login link for a subordinate user.
  Requires the actor to have the appropriate hierarchical supervisory or management role.
  """
  @spec generate_one_time_login_link(User.t(), User.t() | Scope.t(), (String.t() -> String.t())) ::
          {:ok, String.t()} | {:error, :forbidden | :inactive | term()}
  def generate_one_time_login_link(%User{} = target_user, actor, url_builder_fun)
      when is_function(url_builder_fun, 1) do
    cond do
      not target_user.active ->
        {:error, :inactive}

      not ScopeResolver.can_generate_one_time_login?(actor, target_user) ->
        {:error, :forbidden}

      true ->
        {encoded_token, user_token} = UserToken.build_email_token(target_user, "one_time_login")
        insert_user_token!(user_token)
        {:ok, url_builder_fun.(encoded_token)}
    end
  end

  @doc """
  Consumes a one-time login token. If valid, the user is confirmed (if not already),
  the token is deleted from users_tokens, and {:ok, user} is returned.
  """
  @spec consume_one_time_login_token(binary()) ::
          {:ok, User.t()} | {:error, :not_found | :inactive}
  def consume_one_time_login_token(token) when is_binary(token) do
    with {:ok, query} <- UserToken.verify_one_time_login_token_query(token),
         {user, token_record} <- Repo.one(query) do
      cond do
        not user.active ->
          {:error, :inactive}

        is_nil(user.confirmed_at) ->
          Repo.delete!(token_record)

          {:ok, updated_user} =
            user
            |> User.confirm_changeset()
            |> Repo.update()

          {:ok, updated_user}

        true ->
          Repo.delete!(token_record)
          {:ok, user}
      end
    else
      _ -> {:error, :not_found}
    end
  end

  ## Token helper

  defp insert_user_token!(%UserToken{} = user_token) do
    attrs =
      user_token
      |> Map.from_struct()
      |> Map.take([:token, :context, :sent_to, :user_id, :authenticated_at])

    {:ok, created} =
      UserTokenResource
      |> Ash.Changeset.for_create(:create, attrs, actor: system_actor())
      |> Ash.create()

    Repo.get!(UserToken, created.id)
  end

  defp update_user_and_delete_all_tokens(changeset) do
    Repo.transact(fn ->
      with {:ok, user} <- Repo.update(changeset) do
        tokens_to_expire = Repo.all_by(UserToken, user_id: user.id)

        Repo.delete_all(from(t in UserToken, where: t.id in ^Enum.map(tokens_to_expire, & &1.id)))

        {:ok, {user, tokens_to_expire}}
      end
    end)
  end

