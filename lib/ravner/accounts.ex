  @doc "Returns all users ordered by inserted_at with optional preloading."
  @spec list_users(keyword()) :: [User.t()]
  def list_users(opts \\ []) do
    preload = Keyword.get(opts, :preload, [])

    ecto_preload =
      Enum.map(preload, fn
        {:person, _nested} -> :person
        other -> other
      end)

    users =
      from(u in User, order_by: [asc: u.inserted_at])
      |> Repo.all()
      |> Repo.preload(ecto_preload)

    if :person in ecto_preload do
      people = users |> Enum.map(& &1.person) |> Enum.reject(&is_nil/1)

      if people != [] do
        loaded_people = Ash.load!(people, [:organization], authorize?: false)
        people_by_id = Map.new(loaded_people, &{&1.id, &1})

        Enum.map(users, fn u ->
          if u.person do
            %{u | person: Map.get(people_by_id, u.person.id, u.person)}
          else
            u
          end
        end)
      else
        users
      end
    else
      users
    end
  end

  @doc "Creates a user directly (admin flow) with a temporary password."
  @spec admin_create_user(map(), keyword()) :: {:ok, User.t()} | {:error, term()}
  def admin_create_user(attrs, opts \\ []) do
    actor = Keyword.get(opts, :actor, %{role: :admin})

    changeset =
      %User{}
      |> User.admin_changeset(attrs)
      |> User.password_changeset(attrs)
      |> User.confirm_changeset()

    if changeset.valid? do
      user = Ecto.Changeset.apply_changes(changeset)

      attrs = %{
        email: user.email,
        hashed_password: user.hashed_password,
        confirmed_at: user.confirmed_at,
        role: user.role,
        name: user.name,
        active: user.active,
        supervisor_id: user.supervisor_id
      }

      case create_user_via_ash(attrs, changeset, actor) do
        {:ok, created_user} ->
          sync_person_for_user(created_user)
          {:ok, created_user}

        error ->
          error
      end
    else
      {:error, changeset}
    end
  end

  @doc "Updates user role, name or active flag."
  @spec admin_update_user(User.t(), map(), keyword()) :: {:ok, User.t()} | {:error, term()}
  def admin_update_user(%User{} = user, attrs, opts \\ []) do
    actor = Keyword.get(opts, :actor, %{role: :admin})
    changeset = User.role_changeset(user, attrs)

    if changeset.valid? do
      case update_user_resource(user, changeset, actor) do
        {:ok, updated_user} ->
          sync_person_for_user(updated_user)
          {:ok, updated_user}

        error ->
          error
      end
    else
      {:error, changeset}
    end
  end

  @doc """
  Synchronizes a Person inventory record with a User identity account.
  Creates a Person if one doesn't exist, or links an existing one by email or user_id.
  """
  @spec sync_person_for_user(User.t(), map()) ::
          {:ok, Ravner.Inventory.Person.t()} | {:error, term()}
  def sync_person_for_user(%User{} = user, extra_attrs \\ %{}) do
    alias Ravner.Inventory.Person

    existing =
      Repo.one(
        from p in Person,
          where: p.user_id == ^user.id or (is_nil(p.user_id) and p.email == ^user.email),
          limit: 1
      )

    default_role =
      case user.role do
        :project_manager -> "manager"
        :product_owner -> "owner"
        _ -> "developer"
      end

    {first_name, last_name} = parse_name_parts(user.name, user.email)

    attrs =
      %{
        first_name: first_name,
        last_name: last_name,
        email: user.email,
        user_id: user.id
      }
      |> Map.merge(extra_attrs)

    case existing do
      nil ->
        Ravner.Inventory.create_person(
          Map.put_new(attrs, :default_role, default_role),
          actor: %{role: :admin}
        )

      %Person{} = person ->
        person_record = Ravner.Inventory.get_person!(person.id)

        updates =
          %{user_id: user.id, email: user.email}
          |> then(fn m ->
            if (is_nil(person_record.first_name) or person_record.first_name == user.email) and
                 user.name do
              Map.merge(m, %{first_name: first_name, last_name: last_name})
            else
              m
            end
          end)
          |> Map.merge(extra_attrs)

        Ravner.Inventory.update_person(person_record, updates, actor: %{role: :admin})
    end
  end

  defp parse_name_parts(name, fallback_email) when is_binary(name) and byte_size(name) > 0 do
    case String.split(String.trim(name), ~r/\s+/, parts: 2) do
      [first, last] -> {first, last}
      [single] -> {single, "(Member)"}
      _ -> {fallback_email, "(Member)"}
    end
  end

  defp parse_name_parts(_, fallback_email), do: {fallback_email, "(Member)"}

  @doc """
  Ensures every User has a corresponding Person inventory entity.
  """
  @spec backfill_unlinked_users() :: {:ok, non_neg_integer()}
  def backfill_unlinked_users do
    users = list_users()
    Enum.each(users, &sync_person_for_user/1)
    {:ok, length(users)}
  end

  @doc """
  Deletes a user (admin flow).

  Safeguards:
  - Cannot delete yourself.
  - Cannot delete the last admin.
  """
  @spec admin_delete_user(User.t(), keyword()) :: :ok | {:error, term()}
  def admin_delete_user(%User{} = user, opts) do
    actor = Keyword.fetch!(opts, :actor)

    cond do
      actor && actor.id == user.id ->
        {:error, "Cannot delete your own account"}

      user.role == :admin and
          Repo.one(from u in User, where: u.role == :admin, select: count(u.id)) <= 1 ->
        {:error, "Cannot delete the last admin"}

      true ->
        with {:ok, resource} <- Ash.get(UserResource, user.id, actor: system_actor()),
             :ok <- Ash.destroy(resource, actor: actor) do
          :ok
        else
          {:error, %Ash.Error.Forbidden{}} -> {:error, :forbidden}
          {:error, error} -> {:error, error}
        end
    end
  end

  @doc "Promotes the first user (root) to admin role."
  @spec promote_first_user_to_admin() :: :noop | {:ok, User.t()} | {:error, term()}
  def promote_first_user_to_admin do
    case Repo.one(from u in User, order_by: [asc: u.inserted_at], limit: 1) do
      nil -> :noop
      user -> admin_update_user(user, %{role: :admin}, actor: system_actor())
    end
  end

