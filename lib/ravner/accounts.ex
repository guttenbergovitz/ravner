defmodule Ravner.Accounts do
  @moduledoc """
  Identity, authentication, and user governance context.

  This module coordinates user authentication, password lifecycles, session tokens,
  and role-based administrative user management.

  ## Architecture & Governance Split

  - **Authentication Runtime (`Ravner.Accounts.User` Ecto Schema)**:
    Handles session verification, bcrypt password hashing, token validation,
    and magic links generated by Phoenix authentication generators.

  - **Governance & Policy Enforcement (`Ravner.Accounts.UserResource` Ash Resource)**:
    Administrative user mutations (creation, role assignment, active flag toggling, deletion)
    and user invitations (`UserInviteResource`) pass through Ash actions and policies.
    Writes require an `:admin` actor, ensuring that privilege escalation is prevented at the
    data layer regardless of UI presentation.
  """

  import Ecto.Query, warn: false
  alias Ravner.Repo

  alias Ravner.Accounts.{
    ApiToken,
    Scope,
    ScopeResolver,
    User,
    UserInviteResource,
    UserNotifier,
    UserResource,
    UserToken,
    UserTokenResource
  }

  ## Database getters

  @doc """
  Gets a user by email.

  ## Examples

      iex> get_user_by_email("foo@example.com")
      %User{}

      iex> get_user_by_email("unknown@example.com")
      nil

  """
  @spec get_user_by_email(String.t()) :: User.t() | nil
  def get_user_by_email(email) when is_binary(email) do
    Repo.get_by(User, email: email)
  end

  @doc """
  Gets a user by email and password.

  ## Examples

      iex> get_user_by_email_and_password("foo@example.com", "correct_password")
      %User{}

      iex> get_user_by_email_and_password("foo@example.com", "invalid_password")
      nil

  """
  @spec get_user_by_email_and_password(String.t(), String.t()) :: User.t() | nil
  def get_user_by_email_and_password(email, password)
      when is_binary(email) and is_binary(password) do
    user = Repo.get_by(User, email: email)
    if user && user.active && User.valid_password?(user, password), do: user
  end

