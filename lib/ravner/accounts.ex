  @doc "Creates an invite token for a given email and role."
  @spec create_invite(map(), integer(), keyword()) :: {:ok, UserInvite.t()} | {:error, term()}
  def create_invite(attrs, invited_by_id, opts \\ []) do
    actor = Keyword.get(opts, :actor, %{role: :admin})
    token = :crypto.strong_rand_bytes(32) |> Base.url_encode64(padding: false)
    expires_at = DateTime.add(DateTime.utc_now(:second), @invite_ttl_hours * 3600, :second)

    changeset =
      %UserInvite{}
      |> UserInvite.changeset(
        Map.merge(attrs, %{
          "token" => token,
          "invited_by_id" => invited_by_id,
          "expires_at" => expires_at
        })
      )
      |> Ecto.Changeset.put_change(:token, token)

    if changeset.valid? do
      invite = Ecto.Changeset.apply_changes(changeset)

      ash_attrs = %{
        token: invite.token,
        email: invite.email,
        role: invite.role,
        name: invite.name,
        invited_by_id: invite.invited_by_id,
        target_brand_id: invite.target_brand_id,
        target_organization_id: invite.target_organization_id,
        target_project_id: invite.target_project_id,
        supervisor_id: invite.supervisor_id,
        expires_at: invite.expires_at
      }

      case UserInviteResource
           |> Ash.Changeset.for_create(:create, ash_attrs, actor: actor)
           |> Ash.create() do
        {:ok, created} -> {:ok, Repo.get!(UserInvite, created.id)}
        {:error, _} -> {:error, changeset}
      end
    else
      {:error, changeset}
    end
  end

  @doc "Gets a valid (unexpired, unaccepted) invite by token."
  @spec get_valid_invite(String.t()) :: UserInvite.t() | nil
  def get_valid_invite(token) when is_binary(token) do
    trimmed = String.trim(token)
    now = DateTime.utc_now(:second)

    Repo.one(
      from i in UserInvite,
        where: i.token == ^trimmed and is_nil(i.accepted_at) and i.expires_at > ^now
    )
  end

  def get_valid_invite(_), do: nil

  @doc "Accepts an invite: creates the user account and marks the invite used."
  @spec accept_invite(UserInvite.t(), String.t()) :: {:ok, User.t()} | {:error, term()}
  def accept_invite(%UserInvite{} = invite, password) do
    Repo.transaction(fn ->
      changeset =
        %User{}
        |> User.admin_changeset(
          %{
            "email" => invite.email,
            "name" => invite.name,
            "role" => Atom.to_string(invite.role),
            "supervisor_id" => invite.supervisor_id
          },
          validate_unique: true
        )
        |> User.password_changeset(%{"password" => password, "password_confirmation" => password})
        |> User.confirm_changeset()

      if not changeset.valid? do
        Repo.rollback(changeset)
      end

      user = Ecto.Changeset.apply_changes(changeset)

      case create_user_via_ash(
             %{
               email: user.email,
               hashed_password: user.hashed_password,
               confirmed_at: user.confirmed_at,
               role: user.role,
               name: user.name,
               active: user.active,
               supervisor_id: user.supervisor_id
             },
             changeset,
             system_actor()
           ) do
        {:ok, created_user} ->
          link_or_create_person_for_invited_user(created_user, invite)

          accepted_at =
            invite
            |> UserInvite.accept_changeset()
            |> Ecto.Changeset.get_change(:accepted_at)

          {:ok, _invite} = accept_invite_via_ash(invite, accepted_at, system_actor())

          created_user

        {:error, reason} ->
          Repo.rollback(reason)
      end
    end)
  end

  defp link_or_create_person_for_invited_user(created_user, invite) do
    alias Ravner.Inventory.{Brand, Organization, Project, ProjectRole}

    extra_attrs =
      if invite.target_organization_id,
        do: %{organization_id: invite.target_organization_id},
        else: %{}

    admin_actor = %User{role: :admin}

    case sync_person_for_user(created_user, extra_attrs) do
      {:ok, person} ->
        if invite.target_brand_id && invite.role == :brand_manager do
          case Repo.get(Brand, invite.target_brand_id) do
            %Brand{brand_manager_id: nil} = b ->
              Ravner.Inventory.assign_brand_manager(b, person.id, actor: admin_actor)

            _ ->
              :ok
          end
        end

        if invite.target_organization_id && invite.role == :organization_manager do
          case Repo.get(Organization, invite.target_organization_id) do
            %Organization{manager_id: nil} = o ->
              Ravner.Inventory.assign_organization_manager(o, person.id, actor: admin_actor)

            _ ->
              :ok
          end
        end

        if invite.target_project_id do
          case invite.role do
            :project_manager ->
              case Repo.get(Project, invite.target_project_id) do
                %Project{project_manager_id: nil} = p ->
                  Ravner.Inventory.update_project(p, %{project_manager_id: person.id},
                    actor: admin_actor
                  )

                _ ->
                  :ok
              end

            :product_owner ->
              case Repo.get(Project, invite.target_project_id) do
                %Project{product_owner_id: nil} = p ->
                  Ravner.Inventory.update_project(p, %{product_owner_id: person.id},
                    actor: admin_actor
                  )

                _ ->
                  :ok
              end

            _ ->
              :ok
          end

          if invite.role in [:project_manager, :product_owner] do
            role_str = if invite.role == :project_manager, do: "pm", else: "po"

            existing_role =
              Repo.one(
                from pr in ProjectRole,
                  where:
                    pr.project_id == ^invite.target_project_id and pr.person_id == ^person.id and
                      pr.role == ^role_str
              )

            if is_nil(existing_role) do
              Ravner.Inventory.create_project_role(
                %{
                  project_id: invite.target_project_id,
                  person_id: person.id,
                  role: role_str
                },
                actor: admin_actor
              )
            end
          end
        end

        :ok

      _ ->
        :ok
    end
  rescue
    _ -> :ok
  end

  @doc "Lists all invites ordered by newest first."
  @spec list_invites() :: [UserInvite.t()]
  def list_invites do
    Repo.all(from i in UserInvite, order_by: [desc: i.inserted_at], preload: [:invited_by])
  end

  defp create_user_via_ash(attrs, fallback_changeset, actor) do
    require Logger

    case UserResource |> Ash.Changeset.for_create(:create, attrs, actor: actor) |> Ash.create() do
      {:ok, created} ->
        {:ok, Repo.get!(User, created.id)}

      {:error, %Ash.Error.Forbidden{} = err} ->
        Logger.error("Ash Forbidden on user create: #{inspect(err)}, actor: #{inspect(actor)}")
        {:error, :forbidden}

      {:error, err} ->
        Logger.error("Ash error on user create: #{inspect(err)}")
        {:error, Ravner.AshErrorHelpers.to_ecto_changeset(err, fallback_changeset)}
    end
  end

  defp update_user_resource(%User{} = user, changeset, actor) do
    require Logger

    with {:ok, resource} <- Ash.get(UserResource, user.id, actor: system_actor()),
         {:ok, _updated} <-
           resource
           |> Ash.Changeset.for_update(:admin_update, changeset.changes, actor: actor)
           |> Ash.update() do
      {:ok, Repo.get!(User, user.id)}
    else
      {:error, %Ash.Error.Forbidden{} = err} ->
        Logger.error("Ash Forbidden on user update: #{inspect(err)}, actor: #{inspect(actor)}")
        {:error, :forbidden}

      {:error, err} ->
        Logger.error("Ash error on user update: #{inspect(err)}")
        {:error, Ravner.AshErrorHelpers.to_ecto_changeset(err, changeset)}
    end
  end

  defp accept_invite_via_ash(%UserInvite{} = invite, accepted_at, actor) do
    with {:ok, resource} <- Ash.get(UserInviteResource, invite.id, actor: actor) do
      resource
      |> Ash.Changeset.for_update(:accept, %{accepted_at: accepted_at}, actor: actor)
      |> Ash.update()
    end
  end

