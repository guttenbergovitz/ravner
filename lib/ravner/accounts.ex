  def admin_reset_password_manual(%User{} = user, attrs) do
    changeset = User.password_changeset(user, attrs)

    with {:ok, {updated_user, _tokens}} <- update_user_and_delete_all_tokens(changeset) do
      {:ok, updated_user}
    end
  end

