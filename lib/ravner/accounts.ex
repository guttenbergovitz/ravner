  @doc """
  Creates a new API token. Returns `{:ok, token, raw_secret}` on success.
  Requires `:admin` actor.
  """
  @spec create_api_token(map(), keyword()) :: {:ok, ApiToken.t(), String.t()} | {:error, term()}
  def create_api_token(attrs, opts \\ []) do
    actor = Keyword.get(opts, :actor)
    raw_secret = "rav_live_" <> Base.url_encode64(:crypto.strong_rand_bytes(24), padding: false)

    changeset =
      ApiToken
      |> Ash.Changeset.for_create(:create, Map.put(attrs, :token_raw, raw_secret), actor: actor)

    case Ash.create(changeset) do
      {:ok, token} ->
        {:ok, token, raw_secret}

      {:error, error} ->
        {:error, error}
    end
  end

  @doc """
  Revokes an API token immediately.
  """
  @spec revoke_api_token(ApiToken.t(), keyword()) :: {:ok, ApiToken.t()} | {:error, term()}
  def revoke_api_token(%ApiToken{} = token, opts \\ []) do
    actor = Keyword.get(opts, :actor)

    token
    |> Ash.Changeset.for_update(:revoke, %{}, actor: actor)
    |> Ash.update()
  end

  @doc """
  Verifies a raw API token string against database digests and active status.
  Returns `{:ok, token}` if valid, or `{:error, reason}`.
  """
  @spec verify_api_token(String.t()) ::
          {:ok, ApiToken.t()} | {:error, :invalid | :expired | :revoked}
  def verify_api_token(raw_token) when is_binary(raw_token) do
    token_hash = Base.encode16(:crypto.hash(:sha256, raw_token), case: :lower)

    case Repo.get_by(ApiToken, token_hash: token_hash) do
      nil ->
        {:error, :invalid}

      %ApiToken{revoked_at: revoked_at} when not is_nil(revoked_at) ->
        {:error, :revoked}

      %ApiToken{expires_at: expires_at} = token when not is_nil(expires_at) ->
        if DateTime.compare(expires_at, DateTime.utc_now()) == :lt do
          {:error, :expired}
        else
          {:ok, token}
        end

      %ApiToken{} = token ->
        {:ok, token}
    end
  end

  def verify_api_token(_), do: {:error, :invalid}

  @doc """
  Asynchronously or synchronously records API token usage timestamp and remote IP.
  """
  @spec touch_api_token_usage(ApiToken.t(), String.t() | nil) :: :ok
  def touch_api_token_usage(%ApiToken{} = token, remote_ip) do
    # We update directly via Repo to be lightweight and bypass actor enforcement for runtime telemetry
    now = DateTime.utc_now() |> DateTime.truncate(:second)

    from(t in ApiToken, where: t.id == ^token.id)
    |> Repo.update_all(set: [last_used_at: now, last_used_ip: remote_ip])

    :ok
  end

